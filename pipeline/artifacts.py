"""The generated-artifact contract: ONE declaration of what the build produces and what
the publishing commit must therefore carry.

WHY THIS FILE EXISTS.

`docs/CURRENT_STATE.md` is regenerated by `pipeline.run` on every build, and
`test_current_state_doc_is_in_sync` fails if it drifts from the snapshot. Both of those worked
exactly as designed. The file was still stale in the committed repository for forty-one days.

The reason is that three separate things each held their own idea of what a build produces:

  * `refresh.yml` staged a hand-typed `git add data/processed web/public/data`;
  * `pipeline/run.py` built `data_manifest.json` by globbing `data/processed/*.json`;
  * `tests/test_pipeline.py` kept a hand-typed `REQUIRED_WEB_FILES`.

`CURRENT_STATE.md` is in none of those three, because it is not under `data/processed` and is
not a web payload. So the build wrote it, the test read the file the build had just written and
passed, and `git add` never saw it. The tested worktree was correct and the committed repository
was wrong — in every single bot commit from 2026-09-05 to 2026-10-15, twenty-nine of them.

The guard that WOULD have caught it also existed. `ci.yml` was written in iteration 12 precisely
to run the suite against the committed tree with no build. It never ran once on a bot commit:
GitHub does not trigger workflows from pushes authenticated with the default `GITHUB_TOKEN`. A
correct guard, structurally unreachable on exactly the commits that needed it.

So the lesson is not "also stage the doc". It is that a generated artifact must be declared in
one place that the producer, the staging step, the manifest and the tests all read. This module
is that place. Adding an artifact here is what makes it emitted, staged, manifested and asserted;
there is no second list to remember.

HOW THE PIECES USE IT
  * `pipeline/run.py`      — builds `data_manifest.json` from `web_payloads()`.
  * `scripts/staging_paths.py` — prints `commit_paths()` for `refresh.yml` to stage.
  * `scripts/verify_staged.py` — refuses a commit whose staged set is missing a required artifact.
  * `tests/test_pipeline.py`   — asserts presence, mirroring, and the staging contract itself.

Everything here is data, not logic. Paths are repo-relative and POSIX-separated, because they
are compared against `git` output.
"""

from pipeline.config import OPTIONAL_CONTEXT_FILES, PROCESSED, ROOT, WEB_DATA

# ---------------------------------------------------------------------------
# Kinds
# ---------------------------------------------------------------------------
# WEB_PAYLOAD   data/processed/*.json|geojson, mirrored into web/public/data and served.
# DOC           a generated markdown document under docs/. Not served, not mirrored, but
#               committed — future sessions read it as the authoritative handoff.
KIND_WEB_PAYLOAD = "web_payload"
KIND_DOC = "doc"

# ---------------------------------------------------------------------------
# Required web payloads
# ---------------------------------------------------------------------------
# Every artifact a shipped surface reads. Absence of any of these is a release failure, not a
# skipped test: roughly 136 tests are guarded on their artifact existing, so a dropped payload
# without this list would have read as a green run.
#
# This is the one place the set is written down. `tests/test_pipeline.py` imports it rather than
# keeping a parallel copy, and `test_the_required_payload_set_matches_what_the_build_emits`
# fails if the build starts or stops producing something without this list moving.
REQUIRED_WEB_PAYLOADS = (
    # Core index and events.
    "snapshot.json",
    "index_national.json",
    "index_regional.json",
    "incidents.json",
    "assets.json",
    "regions.json",
    "taxonomy.json",
    "refinery_inventory.json",
    # Geometry the map cannot draw without.
    "regions.geojson",
    "assets_lines.geojson",
    "context_land.geojson",
    "context_borders.geojson",
    "ocean.geojson",
    # Iteration 10-11 surfaces: pipeline registry, Data Quality, ledger, A/B, lifecycle.
    "pipeline_registry.json",
    "pipeline_network_quality.json",
    "data_quality.json",
    "build_changes.json",
    "history_series.json",
    "recovery_lifecycle.json",
    "explanations_regional.json",
)

# The manifest never lists itself, so it cannot be validated by the same loop as the others;
# its presence and mirroring are asserted directly. It is still required, and still staged.
MANIFEST = "data_manifest.json"


# ---------------------------------------------------------------------------
# Generated documents
# ---------------------------------------------------------------------------
# Generated prose. `producer` names the module that writes it; `validated_by` names the test
# that fails when it drifts — recorded here so the next reader can see that a declared artifact
# without a guard is an omission, not a design.
GENERATED_DOCS = (
    {
        "path": "docs/CURRENT_STATE.md",
        "producer": "pipeline.current_state",
        "authoritative_source": "data/processed/snapshot.json",
        "validated_by": "test_current_state_doc_is_in_sync",
        "required": True,
        "refresh_managed": True,
        # No volatile fields: it is rendered from the snapshot's analytic content and
        # deliberately carries no wall-clock stamp, so a same-day rerun produces byte-identical
        # output and cannot manufacture an empty "daily refresh" commit.
        "volatile_fields": (),
    },
)


# ---------------------------------------------------------------------------
# Derived views
# ---------------------------------------------------------------------------

def web_payloads(processed=PROCESSED):
    """Every web payload the build actually emitted, as (name, optional) pairs.

    Globbed rather than listed, because the manifest's job is to describe THIS build. The
    declared-vs-emitted comparison is a test's job, not a glob's.
    """
    found = sorted(processed.glob("*.json")) + sorted(processed.glob("*.geojson"))
    return [(p.name, p.name in OPTIONAL_CONTEXT_FILES) for p in found if p.name != MANIFEST]


def required_paths():
    """Repo-relative POSIX paths of every artifact whose absence is a release failure."""
    out = []
    for name in REQUIRED_WEB_PAYLOADS + (MANIFEST,):
        out.append(f"{PROCESSED.relative_to(ROOT).as_posix()}/{name}")
        out.append(f"{WEB_DATA.relative_to(ROOT).as_posix()}/{name}")
    out += [d["path"] for d in GENERATED_DOCS if d["required"]]
    return tuple(out)


def commit_paths():
    """The paths the daily refresh must stage.

    Directories where the whole tree is generated, individual files otherwise. `refresh.yml`
    reads this through `scripts/staging_paths.py` instead of hard-coding a `git add`, so a new
    generated artifact is staged by declaring it here and nowhere else.
    """
    return (
        PROCESSED.relative_to(ROOT).as_posix(),
        WEB_DATA.relative_to(ROOT).as_posix(),
    ) + tuple(d["path"] for d in GENERATED_DOCS if d["refresh_managed"])
